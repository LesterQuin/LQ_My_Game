/**
 * Returns a randomized slice of words for a drawer to choose from.
 * Supports filtering by category ('ALL' or specific category name).
 */
export function getRandomWordOptions(count = 3, excludeWords = [], category = 'ALL') {
  let pool = DRAW_WORDS;

  // Filter by category if specified and not 'ALL'
  if (category && category.toUpperCase() !== 'ALL') {
    const catUpper = category.toUpperCase();
    const filtered = DRAW_WORDS.filter((item) => item.category.toUpperCase() === catUpper);
    if (filtered.length >= count) {
      pool = filtered;
    }
  }

  // Exclude previously used words if possible
  const lowerExcludes = new Set((excludeWords || []).map((w) => (w || '').toLowerCase()));
  const available = pool.filter((item) => !lowerExcludes.has(item.word.toLowerCase()));
  const finalPool = available.length >= count ? available : pool;

  // Shuffle and pick
  const shuffled = [...finalPool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count).map((item) => item.word);
}

/**
 * Formats a hidden word hint (e.g. "_ _ _ _ _")
 * revealedIndices is a Set of indices that should be shown.
 */
export function formatWordHint(word, revealedIndices = new Set()) {
  if (!word) return '';
  return word
    .split('')
    .map((char, index) => {
      if (char === ' ') return '  ';
      if (char === '-') return '-';
      if (revealedIndices.has(index)) return char.toUpperCase();
      return '_';
    })
    .join(' ');
}
